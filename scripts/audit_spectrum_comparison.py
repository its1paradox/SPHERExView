"""Reproduce a saved comparison and independently integrate native sky apertures.

Read-only inputs. Run from the repository root with the existing Python venv.
The AstroToolBox CSVs are generated by CompareAstroToolBox.java using its JAR.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import sys

import astropy.units as u
from astropy.coordinates import SkyCoord
from astropy.io import fits
from astropy.wcs import WCS
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from backend.app import coadd


def cache_file(cache, url):
    return cache / (hashlib.md5(url.encode()).hexdigest() + '.fits')


def independent(record, cache, ra, dec, subdivisions=256):
    """No production aperture, Jacobian, ellipse or calibration-index function.

    Numerically integrate an actual celestial circle using subpixel sky
    separations. Parent detector coordinates use the documented linear WCS A.
    """
    with fits.open(cache_file(cache, record['cutout_url'])) as h:
        header = h['IMAGE'].header
        w = WCS(header)
        target = SkyCoord(ra, dec, unit='deg')
        x, y = w.world_to_pixel(target)
        ys = np.arange(max(0, int(y)-8), min(h['IMAGE'].data.shape[0], int(y)+10))
        xs = np.arange(max(0, int(x)-8), min(h['IMAGE'].data.shape[1], int(x)+10))
        yy, xx = np.meshgrid(ys, xs, indexing='ij')
        sl = np.ix_(ys, xs)
        sci = h['IMAGE'].data[sl].astype(float) * u.Unit(header['BUNIT']).to(u.MJy/u.sr)
        sci -= h['ZODI'].data[sl] * u.Unit(h['ZODI'].header['BUNIT']).to(u.MJy/u.sr)
        var = h['VARIANCE'].data[sl].astype(float) * u.Unit(h['VARIANCE'].header['BUNIT']).to((u.MJy/u.sr)**2)
        flags = h['FLAGS'].data[sl]
        fatal = sum(1 << bit for name, bit in record['mask_bits'].items() if name != 'MP_SOURCE')
        valid = np.isfinite(sci) & np.isfinite(var) & (var > 0) & ((flags & fatal) == 0)
        sky_valid = valid & ((flags & (1 << record['mask_bits']['MP_SOURCE'])) == 0)
        xc = np.rint(header['CRVAL1A'] + (xx+1-header['CRPIX1A'])*header['CDELT1A']).astype(int)
        yc = np.rint(header['CRVAL2A'] + (yy+1-header['CRPIX2A'])*header['CDELT2A']).astype(int)
        with fits.open(cache_file(cache, record['solid_angle_url'])) as area:
            omega = area['IMAGE'].data[yc, xc] * u.Unit(area['IMAGE'].header['BUNIT']).to(u.sr)
        with fits.open(cache_file(cache, record['calibration_url'])) as cal:
            wave = cal['CWAVE'].data[yc, xc] * u.Unit(cal['CWAVE'].header.get('BUNIT','um')).to(u.um)
        sub = (np.arange(subdivisions)+.5)/subdivisions-.5
        dy, dx = np.meshgrid(sub, sub)
        ap, ann = np.zeros(xx.shape), np.zeros(xx.shape)
        for iy, ix in zip(*np.where(valid)):
            a, d = w.pixel_to_world_values(xx[iy,ix]+dx, yy[iy,ix]+dy)
            distance = SkyCoord(a, d, unit='deg').separation(target).arcsec
            ap[iy,ix] = np.mean(distance <= 12.4)
            ann[iy,ix] = np.mean((distance >= 18.6) & (distance <= 31))
        aw = 1e12*ap*omega*valid
        sw = ann*omega*sky_valid
        sw /= sw.sum()
        coeff = aw-aw.sum()*sw
        intensity = np.where(valid,sci,0)
        variance = np.where(valid,var,0)
        return dict(usable_flux=float(np.sum(aw*intensity)), usable_variance=float(np.sum(aw**2*variance)),
                    usable_sky_flux=float(np.sum(coeff*intensity)), usable_sky_variance=float(np.sum(coeff**2*variance)),
                    wavelength=float(np.sum(aw*wave)/aw.sum()))


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--result',type=Path,required=True)
    parser.add_argument('--astro-cache',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args();args.output.mkdir(parents=True,exist_ok=True)
    manifest=json.loads((args.result/'manifest.json').read_text());cache=args.result.parent.parent
    report={'result':str(args.result),'algorithm':manifest['algorithm'],'recipe':manifest['recipe'],
            'manifest_sha256':hashlib.sha256((args.result/'manifest.json').read_bytes()).hexdigest(),
            'separation_arcsec':float(SkyCoord(133.7599588,-7.2449993,unit='deg').separation(SkyCoord(133.7599588,-7.2432771,unit='deg')).arcsec),
            'positions':{},'independent_checks':[]}
    rows=[]
    for epoch in manifest['epochs']:
        with fits.open(args.result/f"spectrum-{epoch['index']}.fits") as h:
            sky_wcs=WCS(h['FLUX'].header).celestial
            for label,y in [('target',19),('screenshot',20)]:
                ra,dec=sky_wcs.pixel_to_world_values(19,y)
                selected=[]
                for j,s in enumerate(epoch['spectra']):
                    values={key:float(h[key.upper()].data[j,y,19]) for key in ('flux','variance','sky_flux','sky_variance','usable_flux','usable_variance','usable_sky_flux','usable_sky_variance','wavelength','aperture_coverage','sky_coverage')}
                    row=dict(position=label,epoch=epoch['index'],ra=float(ra),dec=float(dec),**s,**values)
                    rows.append(row);selected.append(row)
                flux=np.array([r['flux'] for r in selected]);peak=selected[int(np.nanargmax(flux))]
                report['positions'][f"{label}_epoch_{epoch['index']}"]={'ra':float(ra),'dec':float(dec),'total':len(selected),'complete':int(np.isfinite(flux).sum()),'peak':peak,
                    'detector_medians':[{'detector':det,'flux':float(np.nanmedian([r['flux'] for r in selected if r['detector']==det])),
                      'sky_flux':float(np.nanmedian([r['sky_flux'] for r in selected if r['detector']==det]))} for det in range(1,7)]}
                if epoch['index'] == 1:
                    # One complete aperture per detector, plus the actual extreme sample.
                    probes=[next(r for r in selected if r['detector']==det and np.isfinite(r['sky_flux'])) for det in range(1,7)]
                    if peak not in probes: probes.append(peak)
                    for row in probes:
                        record=manifest['inputs'][row['input_index']]
                        direct=independent(record,cache,ra,dec)
                        differences={key:abs(direct[key]-row[key])/max(1,abs(row[key])) for key in direct}
                        report['independent_checks'].append({'position':label,'obs_id':row['obs_id'],'detector':row['detector'],'direct':direct,'production':{k:row[k] for k in direct},'relative_difference':differences})
                        # Near-zero sky-subtracted flux suffers cancellation;
                        # compare quadrature error with its formal uncertainty,
                        # rather than divide by a possibly vanishing flux.
                        for key in direct:
                            if key == 'usable_sky_flux':
                                assert abs(direct[key]-row[key]) < .01*np.sqrt(row['usable_sky_variance'])
                            else:
                                assert differences[key] < .003, report['independent_checks'][-1]
                        print('independent native check',label,row['detector'],max(differences.values()),flush=True)
    # Match reference measurements by actual detector and observation identity.
    atb=[]
    with (args.output/'astrotoolbox-raw.csv').open() as f:
        for row in csv.DictReader(f):
            with fits.open(args.astro_cache/'J133.7599588-7.2449993/cutouts'/row['file']) as h:
                row.update(obs_id=h['IMAGE'].header['OBSID'],mjd=float(h['IMAGE'].header['MJD-AVG']))
            atb.append(row)
    matched=[]
    lookup={(r['obs_id'],r['detector']):r for r in rows if r['position']=='target'}
    for a in atb:
        r=lookup.get((a['obs_id'],int(a['detector'])))
        if r:
            matched.append(dict(obs_id=a['obs_id'],detector=int(a['detector']),epoch=r['epoch'],atb_flux=float(a['flux']),atb_error=float(a['error']),atb_wave=float(a['wavelength']),our_flux=r['usable_sky_flux'],our_wave=r['wavelength'],complete=np.isfinite(r['flux'])))
    report['matched_count']=len(matched)
    report['matched_complete_statistics']=[{'detector':det,'n':len(v:=[r for r in matched if r['detector']==det and r['complete'] and np.isfinite(r['our_flux'])]),
        'median_our_minus_atb_uJy':float(np.median([r['our_flux']-r['atb_flux'] for r in v])),
        'median_wavelength_difference_um':float(np.median([r['our_wave']-r['atb_wave'] for r in v]))} for det in range(1,7)]
    # R7 and old ATB area arrays: compare actual arrays, not version names.
    report['solid_angle_arrays']=[]
    for det in range(1,7):
        rec=next(r for r in manifest['inputs'] if r['detector']==det and r.get('solid_angle_url'))
        old=args.astro_cache/f'sapm/qr2/solid_angle_pixel_map_D{det}_spx_cal-sapm-v2-2025-164.fits'
        with fits.open(old) as a,fits.open(cache_file(cache,rec['solid_angle_url'])) as b:
            report['solid_angle_arrays'].append({'detector':det,'identical':bool(np.array_equal(a['IMAGE'].data,b['IMAGE'].data)),'units':b['IMAGE'].header['BUNIT']})
    for name,data in [('measurements.csv',rows),('matched-exposures.csv',matched)]:
        with (args.output/name).open('w',newline='') as f:
            writer=csv.DictWriter(f,fieldnames=list(data[0]));writer.writeheader();writer.writerows(data)
    (args.output/'audit.json').write_text(json.dumps(report,indent=2,allow_nan=False))
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    fig,axes=plt.subplots(3,1,figsize=(11,10),sharex=True,layout='constrained')
    for ax,label,key,title in [(axes[0],'screenshot','flux','Original screenshot position: ZODI model only'),(axes[1],'screenshot','sky_flux','Same position and exposures: local annulus subtracted'),(axes[2],'target','sky_flux','AstroToolBox coordinate: local annulus subtracted')]:
        selected=[r for r in rows if r['position']==label and r['epoch']==1 and np.isfinite(r[key])]
        ax.errorbar([r['wavelength'] for r in selected],[r[key] for r in selected],yerr=[np.sqrt(r['sky_variance' if key=='sky_flux' else 'variance']) for r in selected],fmt='.',ms=5,lw=.7,label='SPHERExView: second visit, complete apertures')
        ax.axhline(0,color='gray',lw=.5);ax.set_ylabel('Aperture Fν (µJy)');ax.set_title(title);ax.grid(alpha=.2)
    binned=list(csv.DictReader((args.output/'astrotoolbox-binned.csv').open()))
    axes[2].errorbar([float(r['wavelength']) for r in binned],[float(r['flux']) for r in binned],yerr=[float(r['error']) for r in binned],fmt='.',color='tomato',alpha=.65,ms=4,lw=.5,label='Unmodified AstroToolBox 4.6.1: all cached visits, clipped and binned')
    axes[2].legend(fontsize=8);axes[2].set_xlabel('Wavelength (µm)')
    fig.savefig(args.output/'comparison.png',dpi=160)
    print(json.dumps({'matched':len(matched),'statistics':report['matched_complete_statistics']}))


if __name__=='__main__':
    main()
